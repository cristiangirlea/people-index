#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    fn unique(list: &[&str]) -> bool {
        list.iter().collect::<HashSet<_>>().len() == list.len()
    }

    #[test]
    fn vocabularies_are_unique_and_sized() {
        assert!(
            (190..=255).contains(&TITLES.len()),
            "{} titles",
            TITLES.len()
        );
        for list in [
            TITLES,
            ORG_SYLLABLES,
            ORG_SUFFIXES,
            REBRAND_SUFFIXES,
            FIRST_NAMES,
            SKILLS,
            INDUSTRIES,
            TECHNOLOGIES,
            KEYWORDS,
        ] {
            assert!(unique(list));
        }
        let suffixes: HashSet<_> = ORG_SUFFIXES.iter().collect();
        assert!(REBRAND_SUFFIXES.iter().all(|s| !suffixes.contains(s)));
    }
}
